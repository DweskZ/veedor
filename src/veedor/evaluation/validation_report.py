"""Markdown for the generated results block of docs/VALIDATION.md (numbers only)."""

# ruff: noqa: E501 - long Markdown table strings

from __future__ import annotations

import re
from pathlib import Path

BEGIN = "<!-- RESULTS:BEGIN -->"
END = "<!-- RESULTS:END -->"


def _pp(v: float | None) -> str:
    return "n/a" if v is None else f"{v:+.2f}"


def _p(v: float | None) -> str:
    if v is None:
        return "n/a"
    return "<0.001" if v < 0.001 else f"{v:.3f}"


def _signal_table(rows: list[dict]) -> list[str]:
    head = [
        "| Signal | Notes | n with / without | Median saving with / without | Raw median difference (95 % CI) | "
        "Adjusted effect, pp (95 % CI) | p | p Holm | q BH | MDE pp (Holm) |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    out = []
    for r in rows:
        notes = []
        if r["circular"]:
            notes.append("circular / outcome-dependent: separate, not corrected")
        if r["post_award_information"]:
            notes.append("post-award information")
        note = "; ".join(notes) or "-"
        counts = f"{r['n_with']:,} / {r['n_without']:,}"
        if r["status"] != "tested":
            out.append(
                f"| `{r['signal']}` | {note} | {counts} | not testable (fewer than 30 flagged or 10 buyers) | | | | | | |"
            )
            continue
        raw, adj = r["raw"], r["adjusted"]
        mde = f"{r['mde_pp']:.2f}" + (f" ({r['mde_holm_pp']:.2f})" if "mde_holm_pp" in r else "")
        out.append(
            f"| `{r['signal']}` | {note} | {counts} | {raw['median_with']:.3f} / {raw['median_without']:.3f} | "
            f"{raw['difference']:+.3f} ({raw['ci_low']:+.3f} to {raw['ci_high']:+.3f}) | "
            f"{_pp(adj['effect_pp'])} ({_pp(adj['ci_low_pp'])} to {_pp(adj['ci_high_pp'])}) | "
            f"{_p(adj['p_value'])} | {_p(adj.get('p_holm'))} | {_p(adj.get('q_bh'))} | {mde} |"
        )
    return head + out


def _composites(blocks: list[dict]) -> list[str]:
    lines = [
        "| Composite | n | Share with score above 0 | Spearman with saving (95 % CI) | Adjusted effect per 10 points, pp (95 % CI) | p |",
        "|---|---|---|---|---|---|",
    ]
    for b in blocks:
        base = f"| {b['label']} | {b['n']:,} | {b['share_with_score_above_zero']:.3%} |"
        if b["status"] != "tested":
            lines.append(base + " not testable | | |")
            continue
        s, e = b["spearman"], b["effect_per_10_points_pp"]
        lines.append(
            f"{base} {s['rho']:+.4f} ({s['ci_low']:+.4f} to {s['ci_high']:+.4f}) | "
            f"{_pp(e['effect_pp'])} ({_pp(e['ci_low_pp'])} to {_pp(e['ci_high_pp'])}) | {_p(e['p_value'])} |"
        )
    return lines


def _period(title: str, block: dict) -> list[str]:
    y0, y1 = block["years"]
    return [
        f"### {title} ({y0}-{y1})",
        "",
        f"{block['n_processes']:,} competitive processes with budget and award; {block['n_buyers']:,} buyers; "
        f"median saving {block['median_saving']:.3f}. Effects are percentage points of budget on the "
        "winsorised saving, negative meaning lower saving with the signal. The raw median difference is in "
        "saving-ratio units (0.01 = one percentage point).",
        "",
        *_signal_table(block["signals"]),
        "",
        *_composites(block["composites"]),
        "",
    ]


def render_markdown(result: dict) -> str:
    meta, lb = result["meta"], result["list_backtest"]
    lines = [
        "## Results (generated by `veedor evaluate validation`)",
        "",
        f"Plan block hash (sha256): `{meta['plan_sha256']}`. Seed {meta['seed']}; bootstrap replicates "
        f"{meta['n_boot_median']} (medians) and {meta['n_boot_spearman']} (Spearman). Sample: "
        f"{meta['n_sample']:,} processes. A signal needs at least {meta['min_flagged']} flagged processes and "
        f"{meta['min_buyers']} distinct flagged buyers in a period to be tested. All figures are aggregates and "
        "describe the dataset, not any process.",
        "",
        *_period("Exploration period", result["explore"]),
        *_period("Confirmation period (decisive)", result["confirm"]),
    ]
    lines += ["### SRI list back-test and what it can detect", ""]
    ll = result["larger_list"]
    lines.append(
        f"Larger official list obtained: **{'yes' if ll['obtained'] else 'no'}**. Checked {ll['checked_url']} on "
        f"{ll['checked_on']}. {ll['finding']} Only company rows are used in the back-test."
    )
    if "auc" in lb:
        auc, pw = lb["auc"], lb["power"]
        lines += [
            "",
            f"Existing back-test carried over from `eval/backtest.json`: {lb['n_positives']} positive companies "
            f"against {lb['n_unlabelled']:,} unlabelled; AUC {auc['estimate']:.3f} (95 % CI {auc['low']:.3f} to "
            f"{auc['high']:.3f}). Lift in the top 1 % / 5 % / 10 %: {lb['lift_top_1']['estimate']:.2f} / "
            f"{lb['lift_top_5']['estimate']:.2f} / {lb['lift_top_10']['estimate']:.2f} (precision in the top "
            f"fraction is lift x prevalence of {lb['prevalence']:.5f}). Under the null the AUC has a standard "
            f"error of {pw['se_null']:.3f}; at 80 % power only an AUC of about {pw['detectable_auc']:.2f} or "
            "higher could be detected, so the test is inconclusive for any smaller separation.",
        ]
    return "\n".join(lines) + "\n"


def update_doc(path: Path, block: str) -> None:
    text = path.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise ValueError(f"{path} has no results markers.")
    path.write_text(pattern.sub(lambda _m: f"{BEGIN}\n{block}{END}", text))
