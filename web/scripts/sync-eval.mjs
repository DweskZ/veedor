// Copies the figures the /agentes page shows from the repository's generated evaluation files into
// src/data/eval-snapshot.json. Values are copied unchanged (no rounding, no derivation except the sum of
// integer tool-call counts). A missing figure is written as null and the page omits that tile.
// Run from web/: pnpm sync:eval
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const read = (f) => {
  try {
    return JSON.parse(readFileSync(`${root}${f}`, "utf8"));
  } catch {
    return null;
  }
};
const at = (o, ...path) => path.reduce((a, k) => (a == null ? null : (a[k] ?? null)), o);

const inv = read("eval/investigations_run.json");
const grd = read("eval/llm_grounding_runs.json");
const vec = read("eval/vector_search.json");
const bt = read("eval/backtest.json");

const outcomeTotals = (run) => {
  const by = at(run, "tool_calls_by_tool_and_outcome");
  if (!by) return null;
  const t = {};
  for (const outcomes of Object.values(by)) for (const [k, n] of Object.entries(outcomes)) t[k] = (t[k] ?? 0) + n;
  return t;
};
const investigationRun = (run) =>
  run && {
    investigations: run.investigations ?? null,
    dossiers_passing_verification: run.dossiers_passing_verification ?? null,
    errors: run.errors ?? null,
    dossier_modes: run.dossier_modes ?? null,
    model: run.model ?? null,
    tool_calls_by_outcome: outcomeTotals(run),
  };

const snapshot = {
  note: "Generated by scripts/sync-eval.mjs from eval/*.json. Do not edit by hand.",
  investigations: inv && {
    source: "eval/investigations_run.json",
    no_llm: investigationRun(inv.no_llm),
    with_llm: investigationRun(inv.with_llm),
  },
  grounding: grd && {
    source: "eval/llm_grounding_runs.json",
    runs: (grd.runs ?? []).map((r) => ({
      label: r.label ?? null,
      runs: r.runs ?? null,
      model: r.model ?? null,
      llm_passed_first_attempt: r.llm_passed_first_attempt ?? null,
      llm_passed_after_retry: r.llm_passed_after_retry ?? null,
      fell_back_to_template: r.fell_back_to_template ?? null,
      final_dossiers_passing_grounding: r.final_dossiers_passing_grounding ?? null,
      llm_calls: r.llm_calls ?? null,
    })),
  },
  vector: vec && {
    source: "eval/vector_search.json",
    generated_on: vec.generated_on ?? null,
    model: vec.model ?? null,
    dimension: vec.dimension ?? null,
    index_rows: at(vec, "index", "rows"),
    queries: at(vec, "full_index", "queries"),
    k: at(vec, "full_index", "k"),
    agreement_embedding: at(vec, "full_index", "agreement_at_10_cpc5", "embedding"),
    agreement_random: at(vec, "full_index", "agreement_at_10_cpc5", "random_neighbour_baseline"),
    pool_size: at(vec, "pool_experiment", "pool_size"),
    pool_with_cpc_text: at(vec, "pool_experiment", "all_neighbours", "with_cpc_text"),
    pool_description_only: at(vec, "pool_experiment", "all_neighbours", "without_cpc_text"),
    latency_p50_ms: at(vec, "latency", "p50_ms"),
    latency_p95_ms: at(vec, "latency", "p95_ms"),
    caveats: vec.caveats ?? [],
  },
  backtest: bt && {
    source: "eval/backtest.json",
    generated_at: at(bt, "meta", "generated_at"),
    headline: at(bt, "meta", "headline"),
    n_positives: at(bt, "primary", "n_positives"),
    n_unlabelled: at(bt, "primary", "n_unlabelled"),
    auc: at(bt, "primary", "scores", "A:mean", "auc"),
    permutation_p: at(bt, "primary", "permutation_p_auc", "A:mean"),
  },
};

writeFileSync(fileURLToPath(new URL("../src/data/eval-snapshot.json", import.meta.url)), `${JSON.stringify(snapshot, null, 2)}\n`);
console.log("wrote src/data/eval-snapshot.json");
