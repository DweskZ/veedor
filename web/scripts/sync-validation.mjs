// Copies the figures the validation blocks show from the repository's generated eval/validation.json into
// src/data/validation.json. Values are copied unchanged (no rounding, no derivation). The API does not serve this file,
// so the site carries a trimmed copy and every number on the page comes from it.
// Run from web/: pnpm sync:validation
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const OUT = fileURLToPath(new URL("../src/data/validation.json", import.meta.url));

const pick = (o, keys) => Object.fromEntries(keys.map((k) => [k, o?.[k] ?? null]));

const period = (p) => ({
  years: p.years,
  n_processes: p.n_processes,
  n_buyers: p.n_buyers,
  median_saving: p.median_saving,
  signals: p.signals.map((s) => ({
    ...pick(s, ["signal", "status", "post_award_information", "circular", "n_with", "n_without", "n_buyers_with"]),
    adjusted: s.adjusted ? pick(s.adjusted, ["effect_pp", "ci_low_pp", "ci_high_pp", "p_value", "p_holm"]) : null,
    mde_pp: s.mde_pp ?? null,
  })),
  composites: p.composites.map((c) => ({
    ...pick(c, ["label", "signals", "n", "status"]),
    spearman: c.spearman ? pick(c.spearman, ["rho", "ci_low", "ci_high"]) : null,
    effect_per_10_points_pp: c.effect_per_10_points_pp ? pick(c.effect_per_10_points_pp, ["effect_pp", "ci_low_pp", "ci_high_pp"]) : null,
  })),
});

/** Pure: the trimmed object from the parsed eval/validation.json. */
export function buildValidation(v) {
  const lb = v.list_backtest;
  const listSize = /([\d,]+) distinct RUCs/.exec(v.larger_list?.finding ?? "")?.[1]?.replaceAll(",", "");
  return {
    note: "Generated by scripts/sync-validation.mjs from eval/validation.json. Do not edit by hand.",
    source: "eval/validation.json",
    sample: v.meta.n_sample,
    min_flagged: v.meta.min_flagged,
    min_buyers: v.meta.min_buyers,
    explore: period(v.explore),
    confirm: period(v.confirm),
    list_test: {
      official_list_size: listSize ? Number(listSize) : null,
      larger_list_obtained: v.larger_list?.obtained ?? null,
      checked_on: v.larger_list?.checked_on ?? null,
      n_positives: lb.n_positives,
      n_unlabelled: lb.n_unlabelled,
      auc: pick(lb.auc, ["estimate", "low", "high"]),
      se_null: lb.power?.se_null ?? null,
      detectable_auc: lb.power?.detectable_auc ?? null,
    },
    thresholds: {
      verified_years: v.thresholds.verified_years,
      excluded_years: v.thresholds.excluded_years,
      pooled: v.thresholds.pooled.map((t) => ({
        threshold_code: t.threshold_code,
        category: t.category,
        years: t.years,
        budget: pick(t.budget, ["status", "n_window", "observed_below", "expected_below", "observed_above", "expected_above", "excess_bins", "excess_bins_ci", "excess_pct", "excess_pct_ci", "missing_above_pct"]),
      })),
    },
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = JSON.parse(readFileSync(`${root}eval/validation.json`, "utf8"));
  writeFileSync(OUT, `${JSON.stringify(buildValidation(src), null, 2)}\n`);
  console.log("wrote src/data/validation.json");
}
